#!/usr/bin/env python3
"""Analyse AICR follow-up output and emit RESULTS.md.

Usage: analyze-followup.py aicr-followup-<jobid>.out [more.out ...] -o RESULTS.md

Conversions are recomputed from the raw Gb/s lines independently of anything the job
script printed. perftest reports bidirectional rows as the SUM of both directions.
"""
import re
import sys

ENGAGING = {  # healthy reference, GB/s per direction
    "gpu_uni": 49.4, "gpu_bidir": 48.7, "host_uni": 47.8, "host_bidir": 47.6,
}
AICR_PRIOR = {"gpu_uni": 47.5, "gpu_bidir": 27.2, "host_uni": 46.3, "host_bidir": 47.3}

BIDIR_LABELS = {"P1_gpu_both_bidir", "P2_node_gpu_bidir", "P2_node_host_bidir"}


def gbps_to_perdir(gbps, bidir):
    return gbps / (16.0 if bidir else 8.0)


def parse(paths):
    d = {"results": {}, "meta": {}, "scale": {}, "raw": ""}
    text = ""
    for p in paths:
        with open(p, errors="replace") as fh:
            text += fh.read() + "\n"
    d["raw"] = text

    for key, pat in [
        ("date", r"^date\s*:\s*(.+)$"), ("job", r"^job\s*:\s*(.+)$"),
        ("nodes", r"^nodes\s*:\s*(.+)$"), ("size", r"^size\s*:\s*(\S+)"),
        ("perftest", r"^perftest:\s*(.+)$"),
    ]:
        m = re.search(pat, text, re.M)
        if m:
            d["meta"][key] = m.group(1).strip()

    m = re.search(r"resolved: PIX/PXB rail = (\S+)\s+NODE-distance 400G rail = (\S+)", text)
    if m:
        d["meta"]["pixrail"], d["meta"]["noderail"] = m.group(1), m.group(2)

    for m in re.finditer(r"^RESULT (\S+) (\S+)$", text, re.M):
        label, val = m.group(1), m.group(2)
        if label.startswith("P3_"):
            d["scale"][label] = val
        else:
            d["results"][label] = val

    # per-pair lines from the scaling section
    for m in re.finditer(r"=> (\d+) pairs OK, mean per-pair ([\d.]+) GB/s/dir, "
                         r"node total ([\d.]+) GB/s/dir", text):
        d["scale"]["n%s_summary" % m.group(1)] = (
            int(m.group(1)), float(m.group(2)), float(m.group(3)))

    m = re.search(r"GPU-class device.*?(?=\n---|\Z)", text, re.S)
    d["meta"]["has_topology"] = bool(m)
    d["meta"]["pex"] = "PEX890xx" in text
    return d


def fmt(v, bidir):
    if v in (None, "FAILED"):
        return "—"
    try:
        return "%.1f" % gbps_to_perdir(float(v), bidir)
    except ValueError:
        return "—"


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("-")]
    out = "RESULTS.md"
    if "-o" in sys.argv:
        out = sys.argv[sys.argv.index("-o") + 1]
        args = [a for a in args if a != out]
    d = parse(args)
    R, M = d["results"], d["meta"]
    L = []
    A = L.append

    A("# AICR follow-up — narrowing the inter-node GDRDMA defect\n")
    A("Generated by `analyze-followup.py`. All conversions recomputed from raw Gb/s "
      "independently of the job script's own arithmetic: `Gb/s ÷ 8` for GB/s, and `÷ 2` "
      "again for bidirectional rows because perftest reports those as the sum of both "
      "directions.\n")

    A("**Run details**\n")
    A("| | |")
    A("|---|---|")
    for k, lab in [("nodes", "Nodes"), ("job", "Job ID"), ("date", "Date"),
                   ("perftest", "perftest"), ("size", "Message size"),
                   ("pixrail", "PIX/PXB rail"), ("noderail", "NODE-distance rail")]:
        if k in M:
            A("| %s | %s |" % (lab, M[k]))
    A("")

    # ---------------- Part 1: direction isolation ----------------
    A("---\n\n## Part 1 — direction isolation\n")
    A("In an RDMA write the **client** reads its local buffer and writes into the "
      "**server's** buffer. Putting GPU memory on only one side therefore isolates one "
      "direction of the GPU's PCIe traffic.\n")
    A("| Test | What it measures | GB/s per direction | Engaging (healthy) | AICR prior |")
    A("|---|---|---:|---:|---:|")
    rows = [
        ("P1_host_baseline", "host↔host, unidirectional", ENGAGING["host_uni"], AICR_PRIOR["host_uni"]),
        ("P1_read_from_gpu", "**NIC reads from GPU**", None, None),
        ("P1_write_into_gpu", "**NIC writes into GPU**", None, None),
        ("P1_gpu_both_uni", "GPU↔GPU, unidirectional", ENGAGING["gpu_uni"], AICR_PRIOR["gpu_uni"]),
        ("P1_gpu_both_bidir", "**GPU↔GPU, bidirectional**", ENGAGING["gpu_bidir"], AICR_PRIOR["gpu_bidir"]),
    ]
    for label, desc, eng, prior in rows:
        A("| %s | %s | **%s** | %s | %s |" % (
            label.replace("P1_", ""), desc,
            fmt(R.get(label), label in BIDIR_LABELS),
            "%.1f" % eng if eng else "—", "%.1f" % prior if prior else "—"))
    A("")

    rd = R.get("P1_read_from_gpu"); wr = R.get("P1_write_into_gpu")
    if rd not in (None, "FAILED") and wr not in (None, "FAILED"):
        rdv, wrv = gbps_to_perdir(float(rd), False), gbps_to_perdir(float(wr), False)
        ratio = max(rdv, wrv) / min(rdv, wrv) if min(rdv, wrv) > 0 else 0
        A("**Read %.1f vs write %.1f GB/s — ratio %.2f×.**\n" % (rdv, wrv, ratio))
        if ratio >= 1.3:
            slower = "read (NIC reads from GPU)" if rdv < wrv else "write (NIC writes into GPU)"
            A("> **Sharply asymmetric.** The %s direction is the weak one. Per the handoff's "
              "decision table this points at read-completion handling on that path — "
              "`MaxReadRequest` and switch read-completion credits become the prime suspects "
              "(test 4).\n" % slower)
        else:
            A("> **Roughly symmetric.** Neither direction is individually broken, so "
              "read-completion credits are **not** the mechanism. The fault appears only when "
              "the two directions are concurrent, which points at a shared resource rather than "
              "a per-direction throttle.\n")

    # ---------------- Part 2: switch path ----------------
    A("---\n\n## Part 2 — switch path contrast\n")
    A("`PIX`/`PXB` means the GPU and NIC sit under the same PCIe switch, so the transfer is "
      "switch-local peer-to-peer. `NODE` means the GPU reaches the NIC through the root "
      "complex instead, bypassing switch-local P2P. AICR's switch is a **Broadcom PEX890xx**; "
      "Engaging uses a Mellanox MT2910 bridge chain — the last structural difference between "
      "the clusters.\n")
    if any(k.startswith("P2_") for k in R):
        A("| Path | GB/s per direction |")
        A("|---|---:|")
        for label, desc in [("P1_gpu_both_bidir", "PIX/PXB rail, GPU bidirectional (switch-local P2P)"),
                            ("P2_node_gpu_bidir", "NODE rail, GPU bidirectional (via root complex)"),
                            ("P2_node_gpu_uni", "NODE rail, GPU unidirectional"),
                            ("P2_node_host_bidir", "NODE rail, host bidirectional")]:
            if label in R:
                A("| %s | **%s** |" % (desc, fmt(R[label], label in BIDIR_LABELS)))
        A("")
        pix_b = R.get("P1_gpu_both_bidir"); node_b = R.get("P2_node_gpu_bidir")
        if pix_b not in (None, "FAILED") and node_b not in (None, "FAILED"):
            pv, nv = gbps_to_perdir(float(pix_b), True), gbps_to_perdir(float(node_b), True)
            gain = (nv - pv) / pv * 100 if pv else 0
            A("**PIX %.1f vs NODE %.1f GB/s per direction — avoiding switch-local "
              "peer-to-peer is %+.0f%%.**\n" % (pv, nv, gain))
            hostb = R.get("P2_node_host_bidir")
            hv = gbps_to_perdir(float(hostb), True) if hostb not in (None, "FAILED") else None
            if gain >= 20 and nv < 42 and hv and hv >= 42:
                A("> **A gradient, and the switch is the largest single term.** Three paths on "
                  "the same node, worst to best:\n>\n"
                  "> | Path | GB/s/dir |\n> |---|---:|\n"
                  "> | GPU↔NIC **through the switch's P2P routing** (PIX) | %.1f |\n"
                  "> | GPU↔NIC **via the root complex** (NODE) | %.1f |\n"
                  "> | host↔NIC, no GPU (NODE) | %.1f |\n>\n"
                  "> Routing the same GPU traffic around switch-local P2P recovers %+.0f%%, so "
                  "the **Broadcom PEX890xx peer-to-peer path is the dominant contributor** and "
                  "the leading fix target (switch firmware/configuration). But NODE at %.1f is "
                  "still short of the %.1f host baseline, so a second, smaller GPU-side term "
                  "remains — the switch is not the whole story.\n"
                  % (pv, nv, hv, gain, nv, hv))
            elif gain >= 20:
                A("> **Avoiding switch-local peer-to-peer recovers %+.0f%%** — the Broadcom "
                  "PEX890xx P2P path is implicated as the dominant contributor.\n" % gain)
            elif nv >= 42 and pv < 38:
                A("> **The switch is confirmed.** Traffic that avoids switch-local P2P runs at "
                  "full rate while switch-local P2P collapses. Fix is switch "
                  "firmware/configuration on the PEX890xx.\n")
            elif abs(gain) < 10:
                A("> **Both paths behave the same**, so the defect is not specific to "
                  "switch-local peer-to-peer. Attention moves to the NIC or the AMD Turin "
                  "root complex.\n")
            else:
                A("> Partial effect (%+.0f%%) — see the table and raw output.\n" % gain)
    else:
        A("_Not run — no NODE-distance 400 Gb/s rail was resolved on this node._\n")

    # ---------------- Part 3: concurrency ----------------
    A("---\n\n## Part 3 — concurrency scaling\n")
    A("N GPU/NIC pairs driven bidirectionally at once. A flat per-pair rate means a "
      "per-port limit; a falling per-pair rate means a **shared switch resource** "
      "(credits, buffers) saturating — the classic PCIe-switch signature.\n")
    sums = sorted([v for k, v in d["scale"].items() if k.endswith("_summary")])
    if sums:
        A("| Pairs | Mean per-pair (GB/s/dir) | Node total (GB/s/dir) |")
        A("|---:|---:|---:|")
        for n, per, tot in sums:
            A("| %d | %.1f | %.1f |" % (n, per, tot))
        A("")
        if len(sums) >= 2:
            first, last = sums[0], sums[-1]
            drop = (first[1] - last[1]) / first[1] * 100 if first[1] else 0
            A("**Per-pair rate changes %.0f%% going from %d to %d pairs.**\n"
              % (-drop, first[0], last[0]))
            if drop > 15:
                A("> **Shared resource saturating.** Per-pair bandwidth falls as pairs are "
                  "added — strong corroboration that a switch-wide resource is the limit, not "
                  "a per-link property.\n")
            else:
                A("> **Per-port limit.** Per-pair bandwidth holds steady as pairs are added, so "
                  "the constraint is per-link, not a shared switch resource.\n")
    else:
        A("_Not run in this job — concurrency scaling needs ≥2 GPUs per node, and "
          "`b200-devel` caps a user at 2 GPUs total. See the `b200-batch` run._\n")

    # ---------------- Part 4 ----------------
    A("---\n\n## Part 4 — PCIe / firmware reads\n")
    m = re.search(r"=+ PART 4.*?(?=\n#{4,}|\Z)", d["raw"], re.S)
    if m:
        A("```")
        A(m.group(0).strip()[:2500])
        A("```\n")

    # ---------------- topology ----------------
    A("---\n\n## Topology\n")
    for tag, title in [(r"--- 0b\..*?(?=\n--- 0c)", "PCIe bridge chain per GPU"),
                       (r"--- 0c\..*?(?=\n--- 0d)", "PCIe bridge chain per 400 Gb/s NIC"),
                       (r"--- 0d\..*?(?=\n--- 0e)", "Rail rates")]:
        mm = re.search(tag, d["raw"], re.S)
        if mm:
            A("**%s**\n" % title)
            A("```")
            A(mm.group(0).strip()[:2000])
            A("```\n")

    # ---------------- failures ----------------
    A("---\n\n## Anything that failed or was skipped\n")
    fails = [k for k, v in R.items() if v == "FAILED"]
    if fails:
        A("- **FAILED tests:** %s — these produced no parseable result; check the raw output "
          "before drawing conclusions.\n" % ", ".join(sorted(fails)))
    if not sums:
        A("- Part 3 (concurrency scaling) did not run in this job.\n")
    if not fails and sums:
        A("- Nothing failed.\n")

    with open(out, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote %s (%d lines)" % (out, len(L)))


if __name__ == "__main__":
    main()
